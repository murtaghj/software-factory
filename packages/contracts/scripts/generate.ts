// Contract generator (W-003). Reads the read-only reference contracts in docs/spec/contracts and
// writes packages/contracts/src/generated/. Output is a pure function of the inputs: a re-run on
// unchanged inputs produces byte-identical files (checked by scripts/check-generated.sh).
// Usage: node packages/contracts/scripts/generate.ts [--out <dir>]
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';

type Schema = { [key: string]: unknown };
type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };

const repoRoot = join(import.meta.dirname, '..', '..', '..');
const specDir = join(repoRoot, 'docs', 'spec', 'contracts');
const outDir = join(repoRoot, 'packages', 'contracts', 'src', 'generated');

const COPIED = ['domain.schema.json', 'factory-tools.schema.json', 'factory-tools.v1.0.schema.json', 'factory-tools.v1.1.schema.json', 'api.openapi.json'];
const REFERENCE = ['schemas.generated.ts', 'interfaces.ts'];

const sha256 = (text: string): string => createHash('sha256').update(text).digest('hex');
const read = (name: string): string => readFileSync(join(specDir, name), 'utf8');
const isSchema = (v: unknown): v is Schema => typeof v === 'object' && v !== null && !Array.isArray(v);

function header(sources: string[]): string {
  const lines = sources.map((s) => `//   docs/spec/contracts/${s} sha256:${sha256(read(s))}`);
  return ['// GENERATED by packages/contracts/scripts/generate.ts. DO NOT EDIT.', '// Sources:', ...lines, ''].join('\n');
}

function refName(ref: string): string {
  const m = /#\/\$defs\/([A-Za-z0-9_]+)$/.exec(ref);
  if (!m?.[1]) throw new Error(`Unsupported $ref ${ref}`);
  return m[1];
}

function literal(v: unknown): string {
  return JSON.stringify(v);
}

function indent(text: string, depth: number): string {
  return text.split('\n').map((l, i) => (i === 0 ? l : '  '.repeat(depth) + l)).join('\n');
}

// Emits a TypeScript type for the JSON Schema keyword subset used by the reference contracts.
// Conditional (if/then/else), not, contains, string/number bounds and formats are runtime-only
// predicates enforced by the Ajv validators, not by these static types.
function ts(s: unknown, depth = 0): string {
  if (s === true || (isSchema(s) && Object.keys(s).length === 0)) return 'unknown';
  if (!isSchema(s)) throw new Error(`Unsupported schema ${JSON.stringify(s)}`);
  if (Array.isArray(s.oneOf)) return (s.oneOf as unknown[]).map((b) => wrap(ts(b, depth))).join(' | ');
  if (Array.isArray(s.anyOf)) return (s.anyOf as unknown[]).map((b) => wrap(ts(b, depth))).join(' | ');
  if (typeof s.$ref === 'string') return refName(s.$ref);
  if ('const' in s) return literal(s.const);
  if (Array.isArray(s.enum)) return s.enum.map(literal).join(' | ');
  const type = s.type;
  if (Array.isArray(type)) return (type as unknown[]).map((t) => ts({ ...s, type: t }, depth)).join(' | ');
  switch (type) {
    case 'string': return 'string';
    case 'integer':
    case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': return `Array<${ts(s.items ?? true, depth)}>`;
    case 'object': return objectType(s, depth);
    case undefined: {
      if (Array.isArray(s.allOf)) {
        const parts = s.allOf.filter((b) => isSchema(b) && !('if' in b) && !('not' in b)).map((b) => wrap(ts(b, depth)));
        if (parts.length > 0) return parts.join(' & ');
      }
      return 'unknown';
    }
    default: throw new Error(`Unsupported type ${String(type)}`);
  }
}

function wrap(t: string): string {
  return /[|&]/.test(t) && !t.startsWith('{') ? `(${t})` : t;
}

function objectType(s: Schema, depth: number): string {
  const props = isSchema(s.properties) ? s.properties : undefined;
  const ap = s.additionalProperties;
  if (!props) {
    if (ap === false) return 'Record<string, never>';
    if (isSchema(ap)) return `Record<string, ${ts(ap, depth)}>`;
    return 'Record<string, unknown>';
  }
  const required = new Set(Array.isArray(s.required) ? s.required.map(String) : []);
  const lines = Object.entries(props).map(([k, v]) => `  ${literal(k)}${required.has(k) ? '' : '?'}: ${indent(ts(v, depth + 1), 1)};`);
  return `{\n${lines.join('\n')}\n}`;
}

function generateDomain(): string {
  const schema = JSON.parse(read('domain.schema.json')) as { $defs: Record<string, Schema> };
  const out = [header(['domain.schema.json']), '/* eslint-disable */', '// Static types for every $defs entry of the domain 2.0 contract. Validate at runtime with', '// validateContract(); these types do not express cross-field or authority predicates.', ''];
  for (const [name, def] of Object.entries(schema.$defs)) out.push(`export type ${name} = ${ts(def)};`, '');
  out.push(`export const domainDefinitionNames = ${JSON.stringify(Object.keys(schema.$defs), null, 2)} as const;`, '');
  out.push('export type DomainDefinitionName = (typeof domainDefinitionNames)[number];', '');
  out.push('export interface DomainTypes {');
  for (const name of Object.keys(schema.$defs)) out.push(`  ${name}: ${name};`);
  out.push('}', '');
  return out.join('\n');
}

type OpenApiParameter = { name: string; in: 'path' | 'query' | 'header'; required?: boolean; schema: Schema };
type OpenApiOperation = {
  operationId: string;
  parameters?: OpenApiParameter[];
  requestBody?: { required?: boolean; content: Record<string, { schema: Schema }> };
  responses: Record<string, { content?: Record<string, { schema: Schema }> }>;
};

function generateApi(): string {
  const api = JSON.parse(read('api.openapi.json')) as { info: { version: string }; paths: Record<string, Record<string, OpenApiOperation>> };
  const domainNames = new Set(Object.keys((JSON.parse(read('domain.schema.json')) as { $defs: Record<string, unknown> }).$defs));
  const out = [header(['api.openapi.json', 'domain.schema.json']), '/* eslint-disable */', `import type * as D from './domain.ts';`, ''];
  out.push(`export const apiDescriptionVersion = ${literal(api.info.version)};`, '');
  const meta: Record<string, JsonValue> = {};
  const typeLines: string[] = ['export interface ApiOperations {'];
  const tsApi = (schema: Schema): string => {
    const t = ts(schema);
    return t.replace(/\b([A-Z][A-Za-z0-9_]*)\b/g, (m) => (domainNames.has(m) ? `D.${m}` : m));
  };
  for (const [path, methods] of Object.entries(api.paths)) {
    for (const [method, op] of Object.entries(methods)) {
      if (!['get', 'post', 'put', 'patch', 'delete'].includes(method)) continue;
      const params = op.parameters ?? [];
      const group = (where: OpenApiParameter['in']): string => {
        const ps = params.filter((p) => p.in === where);
        if (ps.length === 0) return 'Record<string, never>';
        return `{ ${ps.map((p) => `${literal(p.name)}${p.required === true ? '' : '?'}: ${tsApi(p.schema)}`).join('; ')} }`;
      };
      const body = op.requestBody?.content['application/json']?.schema;
      const responses = Object.entries(op.responses).map(([status, r]) => {
        const content = r.content ?? {};
        const [mediaType, media] = Object.entries(content)[0] ?? [undefined, undefined];
        return { status, mediaType: mediaType ?? null, schema: media?.schema };
      });
      typeLines.push(`  ${op.operationId}: {`,
        `    method: ${literal(method.toUpperCase())};`,
        `    path: ${literal(path)};`,
        `    pathParams: ${group('path')};`,
        `    query: ${group('query')};`,
        `    headers: ${group('header')};`,
        `    requestBody: ${body ? tsApi(body) : 'never'};`,
        `    responses: { ${responses.map((r) => `${literal(r.status)}: ${r.schema ? tsApi(r.schema) : 'void'}`).join('; ')} };`,
        '  };');
      const schemaRef = (schema: Schema | undefined): JsonValue => (schema && typeof schema.$ref === 'string' ? refName(schema.$ref) : null);
      meta[op.operationId] = {
        method: method.toUpperCase(),
        path,
        requestSchema: schemaRef(body),
        requestBodyRequired: op.requestBody?.required === true,
        parameters: params.map((p) => ({ name: p.name, in: p.in, required: p.required === true })),
        responses: Object.fromEntries(responses.map((r) => [r.status, { mediaType: r.mediaType, schema: schemaRef(r.schema) }])),
      };
    }
  }
  typeLines.push('}', '');
  out.push(...typeLines);
  out.push('export type ApiOperationId = keyof ApiOperations;', '');
  out.push(`export const apiOperations = ${JSON.stringify(meta, null, 2)} as const;`, '');
  return out.join('\n');
}

function generateTools(): string {
  const files = ['factory-tools.v1.0.schema.json', 'factory-tools.v1.1.schema.json', 'factory-tools.schema.json'];
  const out = [header(files), '/* eslint-disable */', '// Negotiated factory tool sets. Retained 1.0.0/1.1.0 manifests keep their frozen readers.', ''];
  const sets: Record<string, Record<string, { input: string; output: string }>> = {};
  for (const f of files) {
    const doc = JSON.parse(read(f)) as { properties: { toolSetVersion: { const: string } }; 'x-tools': Record<string, { inputSchema: Schema; outputSchema: Schema }> };
    const version = doc.properties.toolSetVersion.const;
    sets[version] = Object.fromEntries(Object.entries(doc['x-tools']).map(([tool, d]) => [tool, { input: refName(String(d.inputSchema.$ref)), output: refName(String(d.outputSchema.$ref)) }]));
  }
  out.push(`export const factoryToolSets = ${JSON.stringify(sets, null, 2)} as const;`, '');
  out.push('export type FactoryToolSetVersion = keyof typeof factoryToolSets;', '');
  return out.join('\n');
}

function generateReferenceCompat(): string {
  const schema = JSON.parse(read('domain.schema.json')) as { $defs: Record<string, unknown> };
  const out = [header(['schemas.generated.ts', 'domain.schema.json']), '/* eslint-disable */',
    '// Compatibility check: every generated domain type must be mutually assignable with the',
    '// reference schemas.generated.ts shipped in the specification. A mismatch fails typecheck.',
    `import type * as G from './domain.ts';`, `import type * as R from './reference/schemas.generated.ts';`, '',
    '// Mutual assignability alone cannot see a missing optional property, so key sets are compared too.',
    'type Mutual<A, B> = [A] extends [B] ? ([B] extends [A] ? true : false) : false;', 'type Assert<T extends true> = T;', ''];
  for (const name of Object.keys(schema.$defs)) out.push(`export type Compat_${name} = Assert<Mutual<G.${name}, R.${name}>>;`, `export type CompatKeys_${name} = Assert<Mutual<keyof G.${name}, keyof R.${name}>>;`);
  out.push('');
  return out.join('\n');
}

function referenceCopy(name: string): string {
  let text = read(name);
  if (name === 'interfaces.ts') {
    // Rebind the reference service interfaces onto the generated domain types (and make the
    // reference import style valid under nodenext resolution).
    text = text.replace(/from '\.\/schemas\.generated'/g, "from '../domain.ts'");
  }
  return `${header([name])}/* eslint-disable */\n${text}`;
}

export function generate(): Map<string, string> {
  const files = new Map<string, string>();
  for (const name of COPIED) files.set(join('schemas', name), read(name));
  files.set('domain.ts', generateDomain());
  files.set('api.ts', generateApi());
  files.set('tools.ts', generateTools());
  files.set(join('reference', 'schemas.generated.ts'), `${header(['schemas.generated.ts'])}/* eslint-disable */\n${read('schemas.generated.ts')}`);
  files.set(join('reference', 'interfaces.ts'), referenceCopy('interfaces.ts'));
  files.set('reference-compat.ts', generateReferenceCompat());
  const manifest = Object.fromEntries([...COPIED, ...REFERENCE].map((n) => [n, sha256(read(n))]));
  files.set('sources.json', `${JSON.stringify({ specRevision: '1.13', sources: manifest }, null, 2)}\n`);
  return files;
}

function main(): void {
  const files = generate();
  const flag = process.argv.indexOf('--out');
  const target = flag >= 0 && process.argv[flag + 1] ? process.argv[flag + 1] ?? outDir : outDir;
  if (existsSync(target)) rmSync(target, { recursive: true });
  for (const [rel, text] of files) {
    const path = join(target, rel);
    mkdirSync(join(path, '..'), { recursive: true });
    writeFileSync(path, text);
  }
  const count = readdirSync(target, { recursive: true }).length;
  console.log(`Generated ${String(files.size)} contract files (${String(count)} entries) in ${target}`);
}

if (import.meta.url === `file://${process.argv[1] ?? ''}`) main();
